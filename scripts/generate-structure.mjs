#!/usr/bin/env node
// Regenerate docs/STRUCTURE.md from the actual repository tree.
//
//   node scripts/generate-structure.mjs
//
// Generated rather than hand-written, because a hand-maintained file tree is a
// document that starts accurate and silently stops being accurate — which is
// the same failure mode red team F5 found in the case corpus. If this file and
// the repo disagree, re-run this instead of editing the output.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(new URL("..", import.meta.url).pathname);

const SKIP = new Set([
  ".git", "node_modules", "dist", ".next", "build", "coverage",
  ".husky", "local-cases", ".claude",
]);
const SKIP_FILE = /\.(map|tsbuildinfo|lock)$/;

/** Short notes for the paths a reader will ask about first. */
const NOTES = {
  "contracts/velo.compact": "the ZK circuit — the Daubert gate lives here",
  "contracts/managed": "compiled output: bindings, proving and verifier keys (committed, 5.2 MB)",
  "src/engine": "detectors, scoring, exact rational arithmetic — no floats on the decision path",
  "src/seal": "canonicalization, hash-chained custody, bundle sealing, standalone verifier",
  "src/chain": "reads the deployed contract's ledger — no wallet, no keys, no fees",
  "src/witness": "the circuit's private inputs, TypeScript side",
  "src/core": "the operations every interface shares, so none reimplements another (red team F8)",
  "src/mcp": "MCP server — the wallet-shaped tool surface",
  "src/simulate.ts": "end-to-end demo, including both refusals",
  "deploy": "contract deploy, DUST registration and on-chain attestation (Bun)",
  "frontend/src/app/api": "Next.js API routes — seal, verify, attest, chain reads",
  "frontend/src/lib": "wallet connect, corpus loader, contract seam, i18n",
  "cases": "14 synthetic cases, zero PII, all four verdicts",
  "peritos-syntetic": "6 synthetic expert-witness profiles for the credential layers",
  "tests": "root suite — engine, seal, corpus, chain, conformance",
  "scripts": "reproducible verification scripts for specific red team findings",
  "docs": "architecture, cases, red team rounds, learnings, chain runbook",
  "visual": "diagrams and deck backgrounds",
  "demo": "symlinked view of everything a judge needs, without moving the originals",
};

function walk(dir, prefix = "", depth = 0) {
  if (depth > 4) return [];
  const entries = readdirSync(dir)
    .filter((name) => !SKIP.has(name) && !name.startsWith(".") && !SKIP_FILE.test(name))
    .map((name) => ({ name, path: join(dir, name), dir: statSync(join(dir, name)).isDirectory() }))
    .sort((a, b) => (a.dir === b.dir ? a.name.localeCompare(b.name) : a.dir ? -1 : 1));

  const lines = [];
  entries.forEach((entry, i) => {
    const last = i === entries.length - 1;
    const rel = relative(ROOT, entry.path);
    const note = NOTES[rel] ? `   ← ${NOTES[rel]}` : "";
    lines.push(`${prefix}${last ? "└── " : "├── "}${entry.name}${entry.dir ? "/" : ""}${note}`);
    // Directories with a note are summarized, not expanded: the note is the
    // point, and expanding them buries it.
    if (entry.dir && !NOTES[rel]) {
      lines.push(...walk(entry.path, prefix + (last ? "    " : "│   "), depth + 1));
    }
  });
  return lines;
}

const tree = walk(ROOT).join("\n");

const doc = `# Repository structure

Generated by \`node scripts/generate-structure.mjs\` — do not edit by hand. A
hand-maintained file tree starts accurate and silently stops being accurate,
which is the same failure red team F5 found in the case corpus. If this and the
repo disagree, re-run the script.

Directories carrying a note are summarized rather than expanded: the note is
the point. Build output, dependencies and runtime-only state are omitted.

\`\`\`
velo/
${tree}
\`\`\`

## How the pieces relate

\`\`\`
  cases/*.json ──► src/engine ──► src/seal ──► local-cases/*.json
   (evidence)      (verdict)     (sealed)      (never leaves the machine)
                                     │
                                     ├──► src/witness ──► contracts/velo.compact
                                     │     (private)        (proves, on-chain)
                                     │
                                     └──► src/chain ◄── Midnight ledger
                                           (reads back, no wallet needed)

  Three interfaces, one shared implementation in src/core/operations.ts:
    src/mcp/server.ts        agents
    frontend/src/app/api     browser UI
    src/simulate.ts          the demo narrative
\`\`\`

Reading and writing the chain are deliberately separate — see
[\`CHAIN.md\`](./CHAIN.md). Reading needs no wallet, no proving keys and no
fees, so the UI keeps showing real on-chain state on a machine that cannot
produce a proof.
`;

writeFileSync(join(ROOT, "docs", "STRUCTURE.md"), doc);
console.log(`docs/STRUCTURE.md regenerated (${tree.split("\n").length} entries)`);
